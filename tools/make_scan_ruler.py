#!/usr/bin/env python3
"""Generate a printable A4 scan-calibration ruler sheet as a vector PDF.

No dependencies: writes the PDF by hand. All geometry is in millimetres.
Usage: python3 tools/make_scan_ruler.py [output.pdf]
"""
import sys

MM = 72 / 25.4  # PDF points per mm
PAGE_W, PAGE_H = 297.0, 210.0  # A4 landscape

ops = []


def pt(v):
    return f"{v * MM:.3f}"


def lw(w):
    ops.append(f"{pt(w)} w")


def line(x1, y1, x2, y2):
    ops.append(f"{pt(x1)} {pt(y1)} m {pt(x2)} {pt(y2)} l S")


def rect(x, y, w, h):
    ops.append(f"{pt(x)} {pt(y)} {pt(w)} {pt(h)} re S")


def dashed(on):
    ops.append("[3 2] 0 d" if on else "[] 0 d")


def gray(g):
    ops.append(f"{g} G {g} g")


def text(x, y, s, size=2.5, font="F1", center=False):
    s_esc = s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")
    if center:  # rough Helvetica width estimate, good enough for digits
        x -= len(s) * size * 0.278
    ops.append(f"BT /{font} {pt(size)} Tf {pt(x)} {pt(y)} Td ({s_esc}) Tj ET")


def tick_len(i):
    return 6.0 if i % 10 == 0 else 4.0 if i % 5 == 0 else 2.5


def h_ruler(x0, y_top, length, label):
    """Horizontal strip; ticks hang down from the top (cut) edge."""
    x_box, h = x0 - 5, 18
    dashed(True); lw(0.15); gray(0.5)
    rect(x_box, y_top - h, length + 10, h)
    dashed(False); gray(0)
    lw(0.3); line(x0, y_top, x0 + length, y_top)
    for i in range(length + 1):
        lw(0.2 if i % 10 == 0 else 0.12)
        line(x0 + i, y_top, x0 + i, y_top - tick_len(i))
        if i % 10 == 0:
            text(x0 + i, y_top - 9.2, str(i // 10), size=2.8, center=True)
    text(x0, y_top - 15.5, f"{label}  -  cm, 1 mm ticks  -  cut on dashed line, ticks edge goes against the membrane", size=2.3)


def v_ruler(x_left, y0, length, label):
    """Vertical strip; ticks point right from the left (cut) edge."""
    w = 18
    dashed(True); lw(0.15); gray(0.5)
    rect(x_left, y0 - 5, w, length + 10)
    dashed(False); gray(0)
    lw(0.3); line(x_left, y0, x_left, y0 + length)
    for i in range(length + 1):
        lw(0.2 if i % 10 == 0 else 0.12)
        line(x_left, y0 + i, x_left + tick_len(i), y0 + i)
        if i % 10 == 0:
            text(x_left + 7.5, y0 + i - 1.0, str(i // 10), size=2.8)
    text(x_left + 6.5, y0 - 3.8, label, size=2.3)


def calib_square(x, y, s=100):
    lw(0.08); gray(0.6)
    for i in range(10, s, 10):
        line(x + i, y, x + i, y + s)
        line(x, y + i, x + s, y + i)
    gray(0); lw(0.25)
    rect(x, y, s, s)
    # mm ticks along bottom and left edges, inside the square
    for i in range(s + 1):
        lw(0.12)
        line(x + i, y, x + i, y + tick_len(i) * 0.6)
        line(x, y + i, x + tick_len(i) * 0.6, y + i)
    # centre crosshair
    lw(0.15)
    c = s / 2
    line(x + c - 4, y + c, x + c + 4, y + c)
    line(x + c, y + c - 4, x + c, y + c + 4)
    text(x + c, y + s + 2, "100.0 mm", size=3, center=True)
    text(x + s + 2, y + c, "100.0 mm", size=3)


# ---- layout -------------------------------------------------------------
h_ruler(17, 196, 240, "Ruler A")
h_ruler(17, 172, 240, "Ruler B")
v_ruler(272, 17, 170, "Ruler C")
calib_square(17, 30)

tx, ty = 135, 140
text(tx, ty, "A1200 membrane scan ruler", size=6, font="F2")
notes = [
    "PRINTING",
    "  Print at 100% / 'Actual size'. Turn OFF 'Fit to page' / 'Shrink to fit'.",
    "  Check: the square must measure 100.0 mm wide AND 100.0 mm tall",
    "  with a real steel ruler. If not, fix the print settings and reprint.",
    "  (Write the measured values here:  W ______ mm   H ______ mm)",
    "",
    "SCANNING",
    "  Cut out rulers A, B and C along the dashed lines.",
    "  In every scan, place one ruler along the X axis and one along Y",
    "  (scanners can scale the two axes differently).",
    "  Lay rulers flat on the glass, right next to the membrane, ticks touching it.",
    "  Scan at 600 DPI, colour, no auto-crop, no 'descreen'/sharpening.",
    "  Scan both sides. For multi-part scans, keep a ruler visible across",
    "  the overlap so the pieces can be stitched and scaled.",
    "",
    "Printed paper is usually accurate to ~0.2-0.5 %. A real steel ruler in",
    "the scan is even better - use one too if it fits.",
]
for i, n in enumerate(notes):
    bold = n.isupper() and n.strip() != ""
    text(tx, ty - 9 - i * 4.6, n, size=3.0, font="F2" if bold else "F1")

text(17, 14, "Generated by tools/make_scan_ruler.py  -  A4 landscape, vector PDF", size=2.2)

# ---- PDF writer ---------------------------------------------------------
content = "\n".join(ops).encode("latin-1")
objs = [
    b"<< /Type /Catalog /Pages 2 0 R >>",
    b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    (f"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 {pt(PAGE_W)} {pt(PAGE_H)}] "
     f"/Resources << /Font << /F1 5 0 R /F2 6 0 R >> >> /Contents 4 0 R >>").encode(),
    b"<< /Length %d >>\nstream\n" % len(content) + content + b"\nendstream",
    b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>",
]
out = bytearray(b"%PDF-1.4\n")
offsets = []
for i, o in enumerate(objs, 1):
    offsets.append(len(out))
    out += b"%d 0 obj\n" % i + o + b"\nendobj\n"
xref = len(out)
out += b"xref\n0 %d\n0000000000 65535 f \n" % (len(objs) + 1)
for off in offsets:
    out += b"%010d 00000 n \n" % off
out += b"trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n" % (len(objs) + 1, xref)

path = sys.argv[1] if len(sys.argv) > 1 else "docs/scan-ruler.pdf"
with open(path, "wb") as f:
    f.write(out)
print("wrote", path)
